  <View style={[styles.scenarioTile, highlight && styles.scenarioTileActive]}>
    <Text style={styles.scenarioLabel}>{label}</Text>
    <Text style={[styles.scenarioValue, highlight && { color: colors.teal }]}>{formatUsd(value)}</Text>
    <Text style={styles.scenarioSub}>{sub}</Text>
  </View>
